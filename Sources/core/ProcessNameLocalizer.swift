    /// 清洗出匹配用基础名：去 Helper 后缀、去括号段、com.apple. 取末段
    static func baseName(_ raw: String) -> String {
        var n = raw
        // 归一化 Unicode 空格（NBSP/窄 NBSP 等会混进进程名，肉眼不可见但让词典匹配失败）
        for ws in ["\u{00A0}", "\u{202F}", "\u{2007}", "\u{2000}"] {
            n = n.replacingOccurrences(of: ws, with: " ")
        }
        n = n.replacingOccurrences(of: " Helper.*$", with: "", options: .regularExpression)
        n = n.replacingOccurrences(of: "\\s*\\(.*?\\)", with: "", options: .regularExpression)
        n = n.trimmingCharacters(in: .whitespaces)
        if n.isEmpty {
            // 整名被括号包裹的截断名（如 "(AssetMetrics)"）：取括号内文本再试
            n = raw.replacingOccurrences(of: "[()]", with: "", options: .regularExpression)
                .trimmingCharacters(in: .whitespaces)
        }
        if n.hasPrefix("com.apple.") {
            n = n.components(separatedBy: ".").last ?? n
        }
        return n
    }

    /// 命中词典返回中文说明，否则 nil（调用方回退原名）
    static func chineseName(for raw: String) -> String? {
        let base = baseName(raw)
        guard !base.isEmpty else { return nil }
        let lower = base.lowercased()
        if let hit = dict[lower] { return hit }
        // 候选二：com.apple. 长名（如 Safari.SafeBrowsing.Service）不取末段、整段进词典
        // （注意用原始名匹配——baseName 已把前缀剥掉了，评审发现的查找变量错位）
        let lowerRaw = raw.lowercased()
        if lowerRaw.hasPrefix("com.apple.") {
            let full = String(raw.dropFirst("com.apple.".count)).lowercased()
            if let hit = dict[full] { return hit }
        }
        // 前缀规则：XProtect 清理器名字随恶意软件变（已见 17 种），按前缀归一
        if lower.hasPrefix("xprotectremediator") { return "XProtect 恶意软件清理" }
        if lower.hasPrefix("xprotect") { return "XProtect 安全扫描" }
        return nil
    }





